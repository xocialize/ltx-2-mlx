"""Claim C4 — "custom Gemma 4 12B text encoder holds complex prompts together
instead of dropping details across a longer sequence".

Design: a **length-degradation curve**. One scene, progressively extended
(5 -> 12 -> 24 pre-registered elements), generated by LTX-2.3 and LTX-2.5 at
matched seed/geometry/sampler. If the claim holds, 2.5's element recall should
decay more slowly than 2.3's as the prompt lengthens. The *slope* is the
signal; absolute recall is confounded by scene difficulty.

Judge: Gemma-3-12B-it (4-bit) via mlx-vlm — already on disk as the 2.3 text
encoder, and natively multimodal (437 vision-tower tensors). Asked one
YES/NO question per element, per frame.

Safeguards against a judge that just says YES:
  * every element is also asked against a DECOY frame from an unrelated clip;
    a judge that answers YES to absent elements is reported, not trusted.
  * checklists are PRE-REGISTERED in .work/c4/battery.json and must not be
    edited after seeing output.
  * per-element answers are written out so a human can spot-check (the plan
    asks for >=20%).

⚠️ System-level: 2.5 changes BOTH the text encoder and the DiT, so this
measures the pair, not the TE alone.

Usage:
    uv run --no-sync python scripts/measure_c4_adherence.py [--frames 3]
"""

from __future__ import annotations

import argparse
import json
import subprocess
from pathlib import Path

import numpy as np

WORK = Path(".work/c4")
JUDGE = "/Volumes/Satechi/Models/mlx-community/gemma-3-12b-it-4bit"
H, W = 512, 768


def extract(mp4: Path, idx: int) -> Path:
    out = WORK / f"{mp4.stem}_f{idx}.png"
    if not out.exists():
        subprocess.run(["ffmpeg", "-y", "-v", "error", "-i", str(mp4),
                        "-vf", f"select=eq(n\\,{idx})", "-frames:v", "1", str(out)], check=True)
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--frames", type=int, default=3)
    args = ap.parse_args()

    from mlx_vlm import generate, load
    from mlx_vlm.prompt_utils import apply_chat_template

    battery = json.loads((WORK / "battery.json").read_text())
    model, proc = load(JUDGE)
    cfg = model.config

    def ask(img: Path, element: str) -> bool:
        q = (f"Answer with one word, YES or NO. In this video frame, is the following true? "
             f"{element}")
        fmt = apply_chat_template(proc, cfg, q, num_images=1)
        r = generate(model, proc, fmt, [str(img)], max_tokens=5, verbose=False)
        txt = (r.text if hasattr(r, "text") else str(r)).strip().upper()
        return txt.startswith("Y")

    decoy = Path(".work/ltx25-smoke/fox_conv_512_f4.png")  # unrelated scene
    rows, log = [], []
    for level in battery["levels"]:
        n, els = level["n"], level["elements"]
        for tag in ("23", "25"):
            hits, total, decoy_hits = 0, 0, 0
            for seed in (7, 42):
                mp4 = WORK / f"n{n}_s{seed}_{tag}.mp4"
                if not mp4.exists():
                    continue
                idxs = np.linspace(0, 8, args.frames).astype(int)
                for fi in idxs:
                    img = extract(mp4, int(fi))
                    for e in els:
                        ok = ask(img, e)
                        hits += ok
                        total += 1
                        log.append({"level": n, "model": tag, "seed": seed,
                                    "frame": int(fi), "element": e, "answer": bool(ok)})
            for e in els:  # decoy control, once per element per level
                decoy_hits += ask(decoy, e)
            if total:
                rows.append((n, tag, hits / total, decoy_hits / len(els), total))

    (WORK / "c4_answers.json").write_text(json.dumps(log, indent=1))
    print(f"\n  {'elements':>9s} {'model':6s} {'recall':>8s} {'decoy-FP':>9s} {'n':>6s}")
    print(f"  {'-'*9} {'-'*6} {'-'*8} {'-'*9} {'-'*6}")
    for n, tag, rec, fp, tot in rows:
        print(f"  {n:9d} {'2.'+tag[1]:6s} {rec:8.3f} {fp:9.3f} {tot:6d}")

    print("\n  length-degradation slope (recall at max elements - recall at min):")
    for tag in ("23", "25"):
        v = [(n, r) for n, t, r, _, _ in rows if t == tag]
        if len(v) >= 2:
            v.sort()
            print(f"    2.{tag[1]}: {v[0][1]:.3f} @{v[0][0]} -> {v[-1][1]:.3f} @{v[-1][0]}"
                  f"   delta {v[-1][1]-v[0][1]:+.3f}")
    print(f"\n  per-element answers written to {WORK/'c4_answers.json'} for human spot-check")
    print("  ⚠️ decoy-FP is the judge's false-positive rate on an unrelated frame;")
    print("     a high value invalidates the recall column.")


if __name__ == "__main__":
    main()
